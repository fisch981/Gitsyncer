val LocalAppStrings = staticCompositionLocalOf { GermanStrings }

fun getAppStrings(languagePreference: String): AppStrings {
    val lang = if (languagePreference.isBlank() || languagePreference.equals("system", ignoreCase = true)) {
        Locale.getDefault().language
    } else {
        languagePreference
    }
    return if (lang.equals("de", ignoreCase = true)) GermanStrings else EnglishStrings
}
